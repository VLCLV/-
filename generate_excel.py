# ============ 样式定义 ============
header_font = Font(name='微软雅黑', size=11, bold=True, color='FFFFFF')
header_fill = PatternFill(start_color='2F5496', end_color='2F5496', fill_type='solid')
header_align = Alignment(horizontal='center', vertical='center', wrap_text=True)

cell_font = Font(name='微软雅黑', size=10)
cell_align = Alignment(horizontal='left', vertical='top', wrap_text=True)
center_align = Alignment(horizontal='center', vertical='center', wrap_text=True)

key_fill = PatternFill(start_color='FFF2CC', end_color='FFF2CC', fill_type='solid')
period_fill = PatternFill(start_color='D6E4F0', end_color='D6E4F0', fill_type='solid')

thin_border = Border(
    left=Side(style='thin', color='B4C6E7'),
    right=Side(style='thin', color='B4C6E7'),
    top=Side(style='thin', color='B4C6E7'),
    bottom=Side(style='thin', color='B4C6E7')
)

HEADERS = ['时间/时期', '事件/报刊/人物', '核心考点', '历史定位/意义']
COL_WIDTHS = [18, 35, 45, 40]

def create_sheet(wb, title, data):
    ws = wb.create_sheet(title=title)
    # 表头
    for col_idx, header in enumerate(HEADERS, 1):
        cell = ws.cell(row=1, column=col_idx, value=header)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = header_align
        cell.border = thin_border
    # 数据
    for row_idx, row_data in enumerate(data, 2):
        for col_idx, value in enumerate(row_data, 1):
            cell = ws.cell(row=row_idx, column=col_idx, value=value)
            cell.font = cell_font
            cell.border = thin_border
            if col_idx == 1:
                cell.alignment = center_align
                cell.fill = period_fill
            elif col_idx == 3:
                cell.alignment = cell_align
                cell.fill = key_fill
            else:
                cell.alignment = cell_align
    # 列宽
    for col_idx, width in enumerate(COL_WIDTHS, 1):
        ws.column_dimensions[get_column_letter(col_idx)].width = width
    # 冻结首行
    ws.freeze_panes = 'A2'
    # 行高
    ws.row_dimensions[1].height = 30
    for r in range(2, len(data) + 2):
        ws.row_dimensions[r].height = 60
    return ws

